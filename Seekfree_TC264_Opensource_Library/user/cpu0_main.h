#ifndef CPU0_MAIN_H_
#define CPU0_MAIN_H_

#include "zf_common_headfile.h"

/* =====================================================================
 *  App_Cpu0 类型定义
 *
 *  Seekfree 库的 zf_common_clock.c 需要此类型来存储 CPU 频率信息
 *  原始模板的 Cpu0_Main.h 中定义, 这里补上
 * ===================================================================== */
typedef struct {
    struct {
        float32 pllFreq;        /* PLL 频率 */
        float32 cpuFreq;        /* CPU 频率 */
        float32 sysFreq;        /* 系统总线频率 */
        float32 stmFreq;        /* STM 定时器频率 */
    } info;
} App_Cpu0;

/* =====================================================================
 *  PIT 定时器通道配置 (isr.c 中的 ISR 依赖这些配置)
 * ===================================================================== */

/* PIT 通道分配 */
#define IMU_PIT_CHANNEL     (CCU60_CH1)         /* 10ms IMU 采样 */
#define DEBUG_PIT_CHANNEL   (CCU60_CH0)         /* 100ms 调试输出 */

/* =====================================================================
 *  按键引脚定义
 * ===================================================================== */

#define KEY1  (P20_6)           /* 模式切换 */
#define KEY2  (P20_7)           /* 记录锥桶 */
#define KEY3  (P11_2)           /* 记录车库入口 */
#define KEY4  (P11_3)           /* 记录停靠点 */

/* =====================================================================
 *  电机/舵机引脚和参数
 * ===================================================================== */

#define MOTOR_PWM_CH        (ATOM0_CH0_P21_2)
#define MOTOR_PWM_FREQ      (10000)
#define MOTOR_MAX_DUTY      (8000)

#define SERVO_PWM_CH        (ATOM0_CH1_P21_3)
#define SERVO_PWM_FREQ      (50)
#define SERVO_CENTER_US     (750)
#define SERVO_RANGE_US      (250)

/* =====================================================================
 *  导航参数
 * ===================================================================== */

#define MAX_SPEED_MPS       (2.5f)
#define MIN_SPEED_MPS       (0.3f)
#define GARAGE_SPEED_MPS    (0.5f)

/* =====================================================================
 *  ISR 标志变量 (定义在 cpu0_main.c, isr.c 中引用)
 * ===================================================================== */

extern volatile uint8 g_imu_tick;
extern volatile uint8 g_debug_tick;

#endif /* CPU0_MAIN_H_ */
