#ifndef _zf_device_car_light_h_
#define _zf_device_car_light_h_

#include "zf_common_typedef.h"

//-------------------------------------------------------------------------------------------------------------------
//  函数简介      双闪灯显示函数（闪烁模式：0.5s亮 + 0.5s灭，共4次）
//-------------------------------------------------------------------------------------------------------------------
void car_light_double_flash (void);

//-------------------------------------------------------------------------------------------------------------------
//  函数简介      左转灯显示函数（闪烁模式：0.5s亮 + 0.5s灭，共4次）
//-------------------------------------------------------------------------------------------------------------------
void car_light_turn_left    (void);

//-------------------------------------------------------------------------------------------------------------------
//  函数简介      右转灯显示函数（闪烁模式：0.5s亮 + 0.5s灭，共4次）
//-------------------------------------------------------------------------------------------------------------------
void car_light_turn_right   (void);

//-------------------------------------------------------------------------------------------------------------------
//  函数简介      近光灯显示函数（常亮5秒后自动关闭）
//-------------------------------------------------------------------------------------------------------------------
void car_light_low_beam     (void);

//-------------------------------------------------------------------------------------------------------------------
//  函数简介      远光灯显示函数（常亮5秒后自动关闭）
//-------------------------------------------------------------------------------------------------------------------
void car_light_high_beam    (void);

//-------------------------------------------------------------------------------------------------------------------
//  函数简介      雾灯显示函数（常亮5秒后自动关闭）
//-------------------------------------------------------------------------------------------------------------------
void car_light_fog          (void);

#endif
