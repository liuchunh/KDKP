#ifndef CPU0_MAIN_H_
#define CPU0_MAIN_H_

#include "zf_common_headfile.h"

/* =====================================================================
 *  App_Cpu0 类型定义
 *
 *  Seekfree 库的 zf_common_clock.c 需要此类型来存储 CPU 频率信息
 *  原始模板的 Cpu0_Main.h 中定义, 这里补上
 * ===================================================================== */
typedef struct {
    struct {
        float32 pllFreq;        /* PLL 频率 */
        float32 cpuFreq;        /* CPU 频率 */
        float32 sysFreq;        /* 系统总线频率 */
        float32 stmFreq;        /* STM 定时器频率 */
    } info;
} App_Cpu0;

/* =====================================================================
 *  PIT 定时器通道配置 (isr.c 中的 ISR 依赖这些配置)
 * ===================================================================== */

/* PIT 通道分配 */
#define IMU_PIT_CHANNEL     (CCU60_CH1)         /* 10ms IMU 采样 */
#define DEBUG_PIT_CHANNEL   (CCU60_CH0)         /* 100ms 调试输出 */

/* =====================================================================
 *  按键引脚定义
 * ===================================================================== */

#define KEY_MARK     (P20_6)    /* S3: 打点 (记录航点) */
#define KEY_SPEED_UP (P20_7)    /* S4: 加速 */
#define KEY_SLOW_DN  (P11_2)    /* S5: 减速 */
#define KEY_RESET    (P11_3)    /* S6: 刹车 (清空航点+急停) */

/* =====================================================================
 *  ISR 标志变量 (定义在 cpu0_main.c, isr.c 中引用)
 * ===================================================================== */

extern volatile uint8 g_imu_tick;
extern volatile uint8 g_debug_tick;

#endif /* CPU0_MAIN_H_ */
